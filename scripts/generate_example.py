"""
FILE PURPOSE: runs two real pipeline executions (a clean one and one with an injected
schema error that the repair agent fixes) and writes the actual trace to
docs/EXAMPLE_RUN.md. Uses the mock LLM by default so it runs offline; pass --real
to use your configured LLM instead. Nothing in the output is typed by hand.
USAGE: python scripts/generate_example.py [--real]
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from backend.agents.orchestrator import run_agent  # noqa: E402
from backend.config import get_settings  # noqa: E402
from backend.llm.factory import get_llm  # noqa: E402
from backend.llm.mock import MockLLM  # noqa: E402
from backend.tools.schema_tool import build_context  # noqa: E402

Q = "Find the top 5 vehicles by average rating that have received at least 2 ratings."


def block(title, st):
    out = [f"### {title}", "", f"**Question:** {st.user_question}", "",
           f"**Status:** {st.status} | repair attempts: {st.repair_attempts} | steps: {len(st.trace)} | tool calls: {st.tool_calls} | latency: {st.timings['total']:.1f} ms", "",
           f"**Vector ranking (top-K):** {', '.join(st.ranked_tables)}  ", f"**Bridge tables added by relationship expansion:** {', '.join(st.expanded_tables) or 'none'}", "",
           "**Query plan**", "```json", st.query_plan.model_dump_json(indent=2) if st.query_plan else "n/a", "```", "",
           "**Agent trace**", "```text"]
    for t in st.trace:
        out.append(f"[{t.step}] {t.name:<34} {'OK ' if t.ok else 'FAIL'}")
        if t.detail and t.name not in ("Creating query plan",):
            out.append("      " + t.detail.replace("\n", "\n      ")[:400])
    out += ["```", "", "**First SQL generated**", "```sql", st.generated_sql, "```", "", "**Final SQL executed**", "```sql", st.final_sql, "```", ""]
    if st.execution_result and st.execution_result.success:
        r = st.execution_result
        out += ["**Result (first 5 rows)**", "```text", " | ".join(r.columns)] + [" | ".join(str(v) for v in row) for row in r.rows[:5]] + ["```", ""]
    out += ["**Explanation**", "", st.final_answer or st.error or "", ""]
    return "\n".join(out)


if __name__ == "__main__":
    real = "--real" in sys.argv
    s = get_settings()
    ctx = build_context(s)
    llm_clean = get_llm(s) if real else MockLLM()
    llm_fault = get_llm(s) if real else MockLLM(fault_rate=1.0)
    label = f"real LLM ({s.llm_provider})" if real else "MOCK LLM (offline rule-based stub; fault injection used for example 2)"
    a = run_agent(Q, ctx=ctx, llm=llm_clean)
    b = run_agent(Q, ctx=ctx, llm=llm_fault)
    doc = ["# Example runs (generated by scripts/generate_example.py)", "", f"LLM used: **{label}**.",
           "These traces are real program output, not hand-written.", "",
           block("Example 1 - successful query", a), "", block("Example 2 - SQL fails validation, repair agent fixes it", b)]
    Path(__file__).resolve().parent.parent.joinpath("docs", "EXAMPLE_RUN.md").write_text("\n".join(doc), encoding="utf-8")
    print("wrote docs/EXAMPLE_RUN.md")
